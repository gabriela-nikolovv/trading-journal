// Generates supabase/migrations/0004_market_and_taxonomy.sql from the JS taxonomy
// so the database and the app can never drift apart. Re-run after editing taxonomy.js.
import { writeFileSync } from 'node:fs';
import { flattenTaxonomy, TRADINGVIEW_TAXONOMY } from '../packages/engine/src/taxonomy.js';

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const sectors = Object.keys(TRADINGVIEW_TAXONOMY).sort();
const rows = flattenTaxonomy();

const sql = `-- =====================================================================
-- 0004 — Market quotes, TradingView taxonomy, classification cache
-- GENERATED by scripts/gen-taxonomy-migration.mjs — edit taxonomy.js, not this file.
-- =====================================================================

-- 1. Last-known price per symbol (shared reference data; written only by the backend).
create table if not exists public.market_quotes (
  symbol      text primary key,
  price       numeric(18,6) not null,
  currency    text not null default 'USD',
  as_of       timestamptz not null,           -- time of the PRICE, not of our fetch
  session     text check (session in ('regular','pre','post','closed')),
  source      text not null,
  fetched_at  timestamptz not null default now()
);
alter table public.market_quotes enable row level security;
create policy market_quotes_read on public.market_quotes for select using (auth.role() = 'authenticated');

-- 2. TradingView taxonomy. Industry ids are unique per sector so a position can
--    reference (industry, sector) as one composite key.
create unique index if not exists uq_industry_id_sector on public.industries (id, sector_id);

insert into public.sectors (name) values
${sectors.map((s) => `  (${q(s)})`).join(',\n')}
on conflict (name) do nothing;

insert into public.industries (sector_id, name)
select s.id, v.industry from (values
${rows.map((r) => `  (${q(r.sector)}, ${q(r.industry)})`).join(',\n')}
) as v(sector, industry)
join public.sectors s on s.name = v.sector
on conflict (sector_id, name) do nothing;

-- 3. An industry can only be chosen together with ITS sector (spec 23): enforced by the
--    database, not just the dropdown. MATCH SIMPLE lets both be null; the check forbids
--    an industry with no sector.
alter table public.position_instances
  add constraint fk_position_industry_in_sector
  foreign key (industry_id, sector_id) references public.industries (id, sector_id);
alter table public.position_instances
  add constraint chk_industry_needs_sector check (industry_id is null or sector_id is not null);

-- 4. Cached automatic classification per symbol. The user's own choice on a position
--    (position_instances.sector_id / industry_id) always wins over this.
create table if not exists public.symbol_classifications (
  symbol      text primary key,
  sector_id   uuid references public.sectors(id),
  industry_id uuid,
  status      text not null check (status in ('ok','unmapped','unavailable')),
  source      text not null default 'tradingview',
  reason      text,
  fetched_at  timestamptz not null default now(),
  foreign key (industry_id, sector_id) references public.industries (id, sector_id)
);
alter table public.symbol_classifications enable row level security;
create policy symbol_classifications_read on public.symbol_classifications for select using (auth.role() = 'authenticated');
`;
writeFileSync(new URL('../supabase/migrations/0004_market_and_taxonomy.sql', import.meta.url), sql);
console.log(`wrote migration: ${sectors.length} sectors, ${rows.length} industries`);
